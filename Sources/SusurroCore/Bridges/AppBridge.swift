import Foundation

// App bridges (docs/BRIDGES.md): per-app code that talks to one app through
// that app's own channel. Capabilities are separate protocols, so the
// compiler shows what each bridge supports. Bridges are stateless values;
// a latch pin returns a stateful `LatchTarget` that owns the pinned handle.
// All bridge calls block (socket / process / Accessibility): never call them
// on the main thread.

/// A bridge: an identity plus the apps it can talk to.
public protocol AppBridge: Sendable {
    var id: BridgeID { get }
    var bundleIDs: Set<String> { get }
}

/// Text before the cursor for ordinary dictation (spacing, joins). Called off
/// main inside the 250 ms read cap; nil = can't answer quickly, and the
/// generic Accessibility path applies. Must never return secure input.
public protocol ContextReadingBridge: AppBridge {
    /// Short name for logs and the context provider ("appBridge.<name>").
    var name: String { get }
    func textBeforeCursor() -> String?
}

/// What the app passes when the user asks to latch (the app is frontmost).
public struct LatchPinRequest: Sendable, Equatable {
    public var pid: Int32
    public var bundleID: String
    public var appName: String
    /// Generated by Susurro, never from input; names the pin inside the app.
    public var token: Int
    public init(pid: Int32, bundleID: String, appName: String, token: Int) {
        self.pid = pid
        self.bundleID = bundleID
        self.appName = appName
        self.token = token
    }
}

/// Latch: pin the frontmost document position; the returned target then
/// reads context, inserts with read-back, and releases.
public protocol LatchingBridge: AppBridge {
    /// What the target is called in pills: "buffer", "note", "document".
    var documentNoun: String { get }
    func pin(_ request: LatchPinRequest) throws(BridgeError) -> any LatchTarget
    /// A bridge-specific pill for a pin failure (e.g. "turn on the CLI");
    /// nil = the generic "isn't supported" pill.
    func refusalPill(for error: BridgeError) -> String?
}

extension LatchingBridge {
    public func refusalPill(for error: BridgeError) -> String? { nil }
}
